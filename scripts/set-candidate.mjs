#!/usr/bin/env node
/**
 * Point a fixture's entry graph at the package under test.
 *
 * Metro bundles what the entry imports. An installed-but-unimported package is
 * simply absent from the bundle, so a fixture hard-coded to import one library
 * would pass vacuously for every other one. The fixture therefore imports
 * `./candidate`, and this rewrites that file for the package being tested.
 *
 * Usage:
 *   node scripts/set-candidate.mjs <fixture> <package-name>
 *   node scripts/set-candidate.mjs <fixture> --reset
 */

import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const [fixture, pkg] = process.argv.slice(2)
if (!fixture || !pkg) {
  console.error('usage: set-candidate.mjs <fixture> <package-name>|--reset')
  process.exit(1)
}

const target = join('fixtures', fixture, 'candidate.ts')

const stub = `// Rewritten by scripts/set-candidate.mjs for the package under test.
// The committed stub imports nothing, so the fixture builds on its own.
export const candidateName = '(none)'
export const candidateExports: string[] = []
`

const real = `// Generated by scripts/set-candidate.mjs. Do not edit.
import * as candidate from '${pkg}'

export const candidateName = '${pkg}'
// Reading the keys forces the bundler to keep the module: an unreferenced
// namespace import can be dropped, which would make the assertion vacuous.
export const candidateExports: string[] = Object.keys(candidate)
`

writeFileSync(target, pkg === '--reset' ? stub : real)
console.log(
  pkg === '--reset'
    ? `[set-candidate] ${fixture} reset to stub`
    : `[set-candidate] ${fixture} now imports ${pkg}`,
)
