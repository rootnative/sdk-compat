#!/usr/bin/env node
/**
 * Put the demo screens of the `ui` example app into the device app, and write
 * the Maestro flow that visits each one.
 *
 * The example app has one screen for each component. Those screens are the
 * widest use of the library that exists, so the device app shows them as they
 * are. It copies what an app with no Expo can't install: the source of
 * `@rootnative/utils`, which isn't on npm. The stand-ins in `device/stubs`
 * replace the shared files that need the router or the SEO package.
 *
 * Usage: node scripts/device-catalog.mjs <app-dir> <ui-checkout> <flow-file>
 */

import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const [appDir, uiDir, flowFile] = process.argv.slice(2)
if (!appDir || !uiDir || !flowFile) {
  console.error('usage: device-catalog.mjs <app-dir> <ui-checkout> <flow-file>')
  process.exit(1)
}

const device = join(dirname(fileURLToPath(import.meta.url)), '..', 'device')

// Not component screens: the router files, the home screen, and the i18n
// screen, which is a set of links to the localized routes.
const SKIP = new Set(['_layout', 'index', 'i18n'])

const files = (dir, test) =>
  readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && test(e.name))
    .map((e) => e.name)
    .sort()

const copyAll = (from, to, names) => {
  mkdirSync(to, { recursive: true })
  for (const name of names) copyFileSync(join(from, name), join(to, name))
}

const screenFiles = files(
  join(uiDir, 'example/app'),
  (name) =>
    name.endsWith('.tsx') &&
    !name.startsWith('+') &&
    !SKIP.has(name.slice(0, -4)),
)
if (screenFiles.length === 0) throw new Error('No demo screen in the checkout.')
const names = screenFiles.map((file) => file.slice(0, -4))

copyAll(join(uiDir, 'example/app'), join(appDir, 'screens'), screenFiles)
copyAll(
  join(device, 'stubs'),
  join(appDir, 'src'),
  files(join(device, 'stubs'), () => true),
)
copyFileSync(
  join(uiDir, 'example/src/use-hydrated.ts'),
  join(appDir, 'src/use-hydrated.ts'),
)
copyAll(
  join(uiDir, 'packages/utils/src'),
  join(appDir, 'vendor/utils'),
  files(join(uiDir, 'packages/utils/src'), (name) => /\.tsx?$/.test(name)),
)
for (const name of [
  'App.tsx',
  'TouchScreen.tsx',
  'babel.config.js',
  'metro.config.js',
]) {
  copyFileSync(join(device, name), join(appDir, name))
}

writeFileSync(
  join(appDir, 'screens.generated.ts'),
  `// Generated by scripts/device-catalog.mjs. Do not edit.
import type { ComponentType } from 'react'

export const screens: { name: string; load: () => ComponentType }[] = [
${names.map((n) => `  { name: '${n}', load: () => require('./screens/${n}').default },`).join('\n')}
]
`,
)

const visit = (name) => `- assertVisible: 'screen: ${name}'
- waitForAnimationToEnd:
    timeout: 2000
- takeScreenshot: catalog-${name}
- tapOn:
    id: 'next'
`

writeFileSync(
  flowFile,
  `# Generated by scripts/device-catalog.mjs. Do not edit.
# Visits each screen of the device app and takes one screenshot of each. The
# last screen is the summary of the host, which lists each screen that threw.
appId: \${APP_ID}
---
- launchApp
${['touch', ...names].map(visit).join('')}- assertVisible: 'screen: summary'
- takeScreenshot: catalog-summary
- assertVisible: 'errors: none in ${names.length + 1} screens'
`,
)

console.log(`[device-catalog] ${names.length} screens: ${names.join(', ')}`)
